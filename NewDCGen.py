def allocate_stat(details, allocated_points, total_range):
    stat_range = details["range"][1] - details["range"][0] + 1
    max_possible_allocation = allocated_points * (stat_range / total_range)
    attribute_value = random.randint(details["range"][0], int(details["range"][0] + max_possible_allocation))
    cost = abs(attribute_value) * 2
    if cost <= allocated_points:
        return attribute_value, cost
    return allocated_points // 2, allocated_points

def calculate_defenses(character, power_level):
    defenses = {
        "Dodge": character["stats"].get("Agility", {}).get("value", 0) + character["stats"].get("Dodge", {}).get("value", 0),
        "Fortitude": character["stats"].get("Stamina", {}).get("value", 0) + character["stats"].get("Fortitude", {}).get("value", 0),
        "Parry": character["stats"].get("Fighting", {}).get("value", 0) + character["stats"].get("Parry", {}).get("value", 0),
        "Toughness": character["stats"].get("Stamina", {}).get("value", 0) + character["stats"].get("Toughness", {}).get("value", 0),
        "Will": character["stats"].get("Awareness", {}).get("value", 0) + character["stats"].get("Will", {}).get("value", 0),
    }

    # Aggregate additional defense modifications from advantages, skills, and powers
    for category in ["advantages", "skills", "powers"]:
        for item in character.get(category, []):
            for tag, value in item.items():
                if tag in defenses and isinstance(value, int):
                    defenses[tag] += value

    # Validate against the power level rules and add a violation key if necessary
    violation_keys = ["Dodge", "Parry", "Fortitude"]
    for key1, key2 in zip(violation_keys, ["Toughness", "Toughness", "Will"]):
        if defenses[key1] + defenses[key2] > power_level * 2:
            defenses['violation'] = True
            break

    return defenses

def calculate_attack_bonuses(character):
    melee_attack_bonus = character["stats"].get("Fighting", {}).get("value", 0)
    ranged_attack_bonus = character["stats"].get("Dexterity", {}).get("value", 0)

    for advantage in character.get("advantages", []):
        if advantage["name"] == "Close Attack":
            melee_attack_bonus += advantage.get("rank", 0)
        elif advantage["name"] == "Ranged Attack":
            ranged_attack_bonus += advantage.get("rank", 0)

    for skill in character.get("skills", []):
        if skill["name"] == "Close Combat":
            melee_attack_bonus += skill.get("rank", 0)
        elif skill["name"] == "Ranged Combat":
            ranged_attack_bonus += skill.get("rank", 0)

    return melee_attack_bonus, ranged_attack_bonus

def cap_defense_values(character, power_level):
    max_defense_value = power_level * 2
    character["stats"]["Dodge"]["value"] = min(character["stats"]["Dodge"]["value"], max_defense_value)
    character["stats"]["Parry"]["value"] = min(character["stats"]["Parry"]["value"], max_defense_value)
    character["stats"]["Fortitude"]["value"] = min(character["stats"]["Fortitude"]["value"], max_defense_value)
    character["stats"]["Will"]["value"] = min(character["stats"]["Will"]["value"], max_defense_value)
    return character
 
def allocate_stats(character, allocated_points, total_range):
    for stat, details in STATS.items():
        if allocated_points["stats"] <= 0:
            break
        attribute_value, cost = allocate_stat(details, allocated_points["stats"], total_range)
        character["stats"][stat] = {"value": attribute_value, "cost": cost}
        allocated_points["stats"] -= cost
    return character, allocated_points

def calculate_initiative(character):
    initiative = character["stats"].get("Agility", {}).get("value", 0)
    
    for advantage in character.get("advantages", []):
        if advantage["name"] == "Improved Initiative":
            initiative_bonus_per_rank = 4  # Each rank gives +4 to Initiative
            initiative += advantage.get("rank", 0) * initiative_bonus_per_rank
        elif "Initiative" in advantage.get("tags", []):  # for other advantages with Initiative tag
            initiative += advantage.get("rank", 0)
    
    return initiative

def assign_languages(character):
    base_language = "English"  # Define the base language
    for advantage in character["advantages"]:
        if advantage["name"] == "Languages":
            rank = advantage["rank"]
            # Calculate the number of additional languages known based on the advantage rank
            num_additional_languages = 2 ** (rank - 1) - 1  # Subtract 1 because English is always included
            # Ensure that the number of languages does not exceed the total available languages minus one for English
            num_additional_languages = min(num_additional_languages, len(LANGUAGES) - 1)
            # Remove English from the list if it's there to avoid duplication
            selectable_languages = list(LANGUAGES - {base_language})
            selected_languages = random.sample(selectable_languages, k=num_additional_languages)
            selected_languages.append(base_language)  # Add English to the selected languages list
            return selected_languages
    return [base_language]  # Return a list with just English if "Languages" advantage is not found

def allocate_advantages(character, allocated_points, power_level):
    random.shuffle(ADVANTAGES)
    for advantage in ADVANTAGES:
        if allocated_points["advantages"] <= 0:
            break
        if advantage["cost"] <= allocated_points["advantages"]:
            max_rank = advantage.get("max_rank", power_level)
            if max_rank > 0:
                rank = random.randint(1, min(max_rank, allocated_points["advantages"]))
                adjusted_cost = advantage["cost"] * rank
                advantage_entry = {
                    "name": advantage["name"],
                    "rank": rank,
                    "cost": adjusted_cost,
                    **{k: v for k, v in advantage.items() if k in ["Dodge", "Toughness", "Parry", "Fortitude", "Will"]}
                }
                character["advantages"].append(advantage_entry)
                allocated_points["advantages"] -= adjusted_cost
    return character, allocated_points

def allocate_skills(character, allocated_points, power_level):
    random.shuffle(SKILLS)
    for skill in SKILLS:
        if allocated_points["skills"] <= 0:
            break
        if skill["cost"] <= allocated_points["skills"]:
            max_rank = skill.get("max_rank", power_level)
            if max_rank > 0:
                # Ensure that rank is always an even number
                rank = random.randint(1, min(max_rank, allocated_points["skills"])) 
                if rank % 2 != 0:
                    rank -= 1  # Decrement rank by 1 if it's an odd number to make it even
                if rank == 0:
                    continue  # Skip to the next iteration if rank becomes 0
                adjusted_cost = rank / 2
                skill_entry = {
                    "name": skill["name"],
                    "rank": rank,
                    "cost": adjusted_cost,
                    "tags": skill.get("tags", []),
                    **{k: v for k, v in skill.items() if k in ["Dodge", "Toughness", "Parry", "Fortitude", "Will"]}
                }
                character["skills"].append(skill_entry)
                allocated_points["skills"] -= skill["cost"] * rank
    return character, allocated_points

def allocate_powers(character, allocated_points, power_level):
    num_powers = random.randint(0, 5)  # Select a random number of powers between 0 and 5
    selected_power_names = []  # List to keep track of already selected powers

    for _ in range(num_powers):
        if allocated_points["powers"] <= 0:
            break  # Exit the loop if there are no more points to allocate to powers

        random.shuffle(POWERS)
        for power in POWERS:
            power_name = power["name"]

            # Skip the power if it has already been selected
            if power_name in selected_power_names:
                continue

            base_cost = power["cost"]
            max_rank = power.get("max_rank", power_level)

            if max_rank > 0 and base_cost <= allocated_points["powers"]:
                rank = random.randint(1, min(max_rank, allocated_points["powers"]))

                # Randomly select extras and flaws with random ranks
                available_extras = power.get("extras", [])
                available_flaws = power.get("flaws", [])
                selected_extras = random.sample(available_extras, min(len(available_extras), random.randint(1, 4))) if available_extras else []
                selected_flaws = random.sample(available_flaws, min(len(available_flaws), random.randint(0, 2))) if available_flaws else []

                selected_extras_with_ranks = [(extra, random.randint(1, min(max_rank, rank))) for extra in selected_extras]
                selected_flaws_with_ranks = [(flaw, random.randint(1, min(max_rank, rank))) for flaw in selected_flaws]

                # Calculate the adjusted cost
                total_cost, adjusted_cost_per_rank, adjusted_flats = calculate_modified_cost(
                    base_cost, rank, selected_extras_with_ranks, selected_flaws_with_ranks
                )

                if total_cost <= allocated_points["powers"]:
                    power_entry = {
                        "name": power_name,
                        "rank": rank,
                        "base_cost": base_cost,
                        "adjusted_cost_per_rank": adjusted_cost_per_rank,
                        "adjusted_flats": adjusted_flats,
                        "extras": [extra[0] for extra in selected_extras_with_ranks],
                        "extras_ranks": [extra[1] for extra in selected_extras_with_ranks],
                        "flaws": [flaw[0] for flaw in selected_flaws_with_ranks],
                        "flaws_ranks": [flaw[1] for flaw in selected_flaws_with_ranks],
                        "cost": total_cost
                    }
                    character["powers"].append(power_entry)
                    selected_power_names.append(power_name)  # Add the power name to the list of selected powers
                    allocated_points["powers"] -= total_cost
                    break  # Exit the inner loop after adding a power

    return character, allocated_points

def calculate_modified_cost(base_cost, rank, selected_extras, selected_flaws):
    adjusted_cost_per_rank = base_cost
    adjusted_flats = 0

    for extra_name, extra_rank in selected_extras:
        extra = EXTRAS[extra_name]
        if extra["type"] == "per_rank":
            adjusted_cost_per_rank += extra_rank
        elif extra["type"] == "flat_per_rank":
            adjusted_flats += extra_rank

    for flaw_name, flaw_rank in selected_flaws:
        flaw = FLAWS[flaw_name]
        if flaw["type"] == "per_rank":
            adjusted_cost_per_rank -= flaw_rank
        elif flaw["type"] == "flat_per_rank":
            adjusted_flats -= flaw_rank

    total_cost = (rank * adjusted_cost_per_rank) + adjusted_flats
    total_cost = max(base_cost, total_cost)

    return total_cost, adjusted_cost_per_rank, adjusted_flats

def calculate_adjusted_cost(extras, flaws):
    total_extra_cost = sum(extra['per_rank'] for extra in extras)
    total_flaw_cost = sum(flaw['per_rank'] for flaw in flaws)
    adjusted_cost_per_rank = total_extra_cost - total_flaw_cost
    return adjusted_cost_per_rank

def calculate_total_cost(base_cost, adjusted_cost_per_rank, rank, flat_modifiers, character):
    total_cost = (adjusted_cost_per_rank + base_cost * rank) + sum(flat_modifiers)
    return total_cost

