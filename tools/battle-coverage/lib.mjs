// Shared pieces of the battle coverage report: loading the list, counting it, and writing it as markdown.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const KINDS = ['effect', 'extra', 'flaw', 'advantage', 'skill', 'action', 'maneuver', 'stance', 'style extra', 'style flaw', 'condition', 'rule'];
export const STATUSES = ['full', 'partial', 'none', 'n/a'];
// Kinds whose names are curated here rather than checked against the rules data.
export const FREE_KINDS = ['skill', 'action', 'maneuver', 'stance', 'style extra', 'style flaw', 'condition', 'rule'];

const TITLES = { effect: 'Effects', extra: 'Extras', flaw: 'Flaws', advantage: 'Advantages', skill: 'Skills', action: 'Actions', maneuver: 'Maneuvers', stance: 'Fighting style stances', 'style extra': 'Fighting style extras', 'style flaw': 'Fighting style flaws', condition: 'Conditions', rule: 'Rules' };
const COVERAGE_FILE = new URL('./coverage.json', import.meta.url);
const GENERATED_FILE = new URL('../../src/generated/battle-coverage.js', import.meta.url);

export const coveragePath = () => fileURLToPath(COVERAGE_FILE);
export function loadCoverage() { return JSON.parse(readFileSync(COVERAGE_FILE, 'utf8')); }

/** Counts per kind and status, plus the share of fight-relevant rules that are full or partial. */
export function summarize(entries) {
  const rows = KINDS.map((kind) => {
    const mine = entries.filter((e) => e.kind === kind);
    const n = (s) => mine.filter((e) => e.status === s).length;
    return { kind, total: mine.length, full: n('full'), partial: n('partial'), none: n('none'), na: n('n/a') };
  });
  const sum = (key) => rows.reduce((s, r) => s + r[key], 0);
  const all = { kind: 'all', total: sum('total'), full: sum('full'), partial: sum('partial'), none: sum('none'), na: sum('na') };
  return [...rows, all].map((r) => ({ ...r, percent: percentOf(r) }));
}

function percentOf(r) {
  const relevant = r.full + r.partial + r.none;
  return relevant ? Math.round((100 * (r.full + r.partial)) / relevant) : 0;
}

const pad = (v, w) => String(v).padEnd(w);
const padL = (v, w) => String(v).padStart(w);

/** The summary as a plain text table for the terminal. */
export function summaryText(entries) {
  const head = `${pad('kind', 11)}${padL('total', 7)}${padL('full', 7)}${padL('partial', 9)}${padL('none', 7)}${padL('n/a', 7)}${padL('covered', 10)}`;
  const body = summarize(entries).map((r) => `${pad(r.kind, 11)}${padL(r.total, 7)}${padL(r.full, 7)}${padL(r.partial, 9)}${padL(r.none, 7)}${padL(r.na, 7)}${padL(`${r.percent}%`, 10)}`);
  return [head, ...body].join('\n');
}

const cell = (s) => String(s ?? '').replace(/\|/g, '/');

/** The whole docs/battle-coverage.md: a summary table, then one table per kind. */
export function markdown(entries) {
  const out = ['# Battle engine coverage', '',
    'Which rules of the DC Adventures rules data the Battle Room engine (`src/engine/battle/` plus `src/engine/derive.js`) simulates.',
    'This file is generated by `node tools/battle-coverage/report.mjs` from `tools/battle-coverage/coverage.json`; edit the JSON, not this file.', '',
    'Status: **full** is simulated as the book says, **partial** is simulated but simplified (the note says how), **none** is not simulated, **n/a** has no meaning in a fight.',
    '"Covered" is the share of fight-relevant rules (everything except n/a) that are full or partial.', '',
    '## Summary', '', '| Kind | Total | Full | Partial | None | n/a | Covered |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: |'];
  for (const r of summarize(entries)) out.push(`| ${r.kind} | ${r.total} | ${r.full} | ${r.partial} | ${r.none} | ${r.na} | ${r.percent}% |`);
  for (const kind of KINDS) {
    out.push('', `## ${TITLES[kind]}`, '', '| Name | Status | Note | Source |', '| --- | --- | --- | --- |');
    for (const e of entries.filter((x) => x.kind === kind)) out.push(`| ${cell(e.name)} | ${e.status} | ${cell(e.note)} | ${cell(e.source)} |`);
  }
  return out.join('\n') + '\n';
}

/**
 * The module the app ships (src/generated/battle-coverage.js): every entry that matters to a fighter's build report, as
 * { kind, name, status, note }. Entries that are n/a are left out, and a full one needs no note.
 */
export function generatedModule(entries) {
  const slim = entries.filter((e) => e.status !== 'n/a').map((e) => ({ kind: e.kind, name: e.name, status: e.status, ...(e.status === 'full' ? {} : { note: e.note }) }));
  return `// Generated by tools/battle-coverage/report.mjs (and tools/build.mjs data) from tools/battle-coverage/coverage.json. Do not edit by hand.
export const BATTLE_COVERAGE = ${JSON.stringify(slim)};
`;
}

/** Write the shipped module next to rulesdata.js. */
export function writeGenerated(entries) {
  mkdirSync(fileURLToPath(new URL('./', GENERATED_FILE)), { recursive: true });
  writeFileSync(GENERATED_FILE, generatedModule(entries));
  return fileURLToPath(GENERATED_FILE);
}
