// Build steps, no dependencies:
//   node tools/build.mjs data  -> src/generated/rulesdata.js (all JSON data as one module)
//   node tools/build.mjs all   -> data + DCUGen.html (one self-contained file, double-click to open)

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { loadCoverage, writeGenerated } from './battle-coverage/lib.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'data');
const SRC = path.join(ROOT, 'src');
const read = (p) => fs.readFileSync(p, 'utf8');
const readJson = (p) => JSON.parse(read(p));

function jsonFolder(dir) {
  const full = path.join(DATA, dir);
  if (!fs.existsSync(full)) return {};
  return Object.fromEntries(
    fs.readdirSync(full).filter((f) => f.endsWith('.json')).sort()
      .map((f) => [path.basename(f, '.json'), readJson(path.join(full, f))]),
  );
}

/**
 * The version shown in the app. CI sets DCUGEN_VERSION to the release (6.1.<build number>); other builds
 * (the website, local) say which commit they came from when they know it.
 */
function appVersion() {
  if (process.env.DCUGEN_VERSION) return process.env.DCUGEN_VERSION;
  const base = readJson(path.join(ROOT, 'package.json')).version;
  const sha = process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA || '';
  return sha ? `${base}+${sha.slice(0, 7)}` : `${base}-dev`;
}

/** A JS string literal in single quotes: JSON has few of those, so it stays about the size of the JSON. (Line and paragraph separators are fine in string literals since ES2019.) */
const singleQuoted = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function buildData() {
  const opt = (name, fallback) => (fs.existsSync(path.join(DATA, name)) ? readJson(path.join(DATA, name)) : fallback);
  const raw = {
    effects: readJson(path.join(DATA, 'effects.json')),
    modifiers: readJson(path.join(DATA, 'modifiers.json')),
    specificModifiers: Object.fromEntries(
      Object.entries(readJson(path.join(DATA, 'specific_modifiers.json'))).filter(([k]) => !k.startsWith('_')),
    ),
    advantages: opt('advantages.json', []),
    skills: readJson(path.join(DATA, 'skills.json')),
    skillGuide: opt('skill_guide.json', []),
    equipment: opt('equipment.json', { weapons: [], armor: [], gear: [], devices: [] }),
    styles: opt('styles.json', []),
    stances: opt('stances.json', []),
    maneuvers: opt('maneuvers.json', []),
    archetypes: opt('archetypes.json', []),
    themes: opt('themes.json', []),
    flavor: jsonFolder('flavor'),
    catalog: jsonFolder('catalog'),
    reference: opt('reference.json', null),
    vehicles: opt('vehicles.json', null), headquarters: opt('headquarters.json', null),
    gm: jsonFolder('gm'),
    lifepath: jsonFolder('lifepath'),
    gear: jsonFolder('gear'),
    spaceRules: opt('space_rules.json', null),
  };
  const out = path.join(SRC, 'generated');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(
    path.join(out, 'rulesdata.js'),
    // JSON.parse of a string starts faster than the same data as an object literal (the parser is far simpler).
    `// Generated by tools/build.mjs from data/*.json. Do not edit by hand.\nexport const RAW = JSON.parse(${singleQuoted(JSON.stringify(raw))});\n`
      // Character keys rebuild people from seeds, so they carry a stamp of the data they were made with.
      + `export const DATA_VERSION = ${JSON.stringify(crypto.createHash('sha1').update(JSON.stringify(raw)).digest('hex').slice(0, 6))};\n`
      // Outside RAW on purpose: release notes and the version must not change DATA_VERSION (and so old keys).
      + `export const APP_VERSION = ${JSON.stringify(appVersion())};\n`
      + `export const APP_COMMIT = ${JSON.stringify(process.env.VERCEL_GIT_COMMIT_SHA || process.env.GITHUB_SHA || '')};\n`
      + `export const CHANGELOG = ${JSON.stringify(opt('changelog.json', []))};\n`
      // Homebrew packs that ship with the app (data/packs): switched on by choice, so seeds never change.
      + `export const PACKS = ${JSON.stringify(Object.values(jsonFolder('packs')))};\n`,
  );
  writeGenerated(loadCoverage()); // src/generated/battle-coverage.js: what the Battle Room simulates, for each fighter's build report
  const catalogCount = Object.values(raw.catalog).reduce((s, l) => s + l.length, 0);
  console.log(`data: ${raw.effects.length} effects, ${raw.advantages.length} advantages, ${raw.archetypes.length} archetypes, ${raw.themes.length} themes, ${catalogCount} catalog entries`);
}

// ---- tiny bundler: ES modules -> one script --------------------------------------------
// Each module becomes a function scope in a registry; imports become destructuring from it.

const IMPORT_RE = /^import\s+\{([\s\S]*?)\}\s+from\s+['"](.+?)['"];?\s*$/gm;

function collect(entry, seen = new Set(), order = []) {
  const file = path.resolve(entry);
  if (seen.has(file)) return order;
  seen.add(file);
  const code = read(file);
  for (const m of code.matchAll(IMPORT_RE)) collect(path.resolve(path.dirname(file), m[2]), seen, order);
  order.push(file);
  return order;
}

// The bundler only understands the forms the code base uses. Anything else fails the build loudly instead of
// producing a page that breaks when it runs.
function checkForms(file, code) {
  const rel = path.relative(ROOT, file);
  const bad = [];
  code.split(/\r?\n/).forEach((line, i) => {
    if (/^\s*import\s/.test(line) && !/^import\s+\{/.test(line)) bad.push(`${rel}:${i + 1}: only "import { a, b } from './x.js';" is supported`);
    // Nothing after the semicolon (a trailing comment hides the import from the bundler).
    if (/^import\s+\{.*\}\s*from\s/.test(line) && !/^import\s+\{.*\}\s*from\s+['"][^'"]+['"];?\s*$/.test(line)) bad.push(`${rel}:${i + 1}: put nothing after an import (move the comment above it)`);
    if (/^\s*import\s*\(/.test(line) || /[^.\w]import\s*\(\s*['"`]/.test(line)) bad.push(`${rel}:${i + 1}: dynamic import() is not supported`);
    if (/^export\s+\*/.test(line)) bad.push(`${rel}:${i + 1}: "export *" is not supported`);
    if (/^export\s+default\s+(?!(async\s+)?function|class)/.test(line)) bad.push(`${rel}:${i + 1}: "export default <expression>" is not supported`);
    if (/^export\s+(var|let|const)\s*[{[]/.test(line)) bad.push(`${rel}:${i + 1}: destructuring exports are not supported`);
  });
  if (bad.length) throw new Error(`build: unsupported module syntax\n  ${bad.join('\n  ')}`);
}

function wrapModule(file) {
  const id = path.relative(ROOT, file).split(path.sep).join('/');
  let code = read(file);
  checkForms(file, code);
  const exported = new Set();
  code = code.replace(IMPORT_RE, (_, names, from) => {
    const dep = path.relative(ROOT, path.resolve(path.dirname(file), from)).split(path.sep).join('/');
    const list = names.split(',').map((n) => n.trim()).filter(Boolean).map((n) => n.replace(/\s+as\s+/, ': '));
    return `const { ${list.join(', ')} } = __mods[${JSON.stringify(dep)}];`;
  });
  code = code.replace(/^export\s+\{([^}]*)\};?\s*$/gm, (_, names) => {
    for (const n of names.split(',').map((x) => x.trim()).filter(Boolean)) exported.add(n.replace(/\s+as\s+/, ': '));
    return '';
  });
  code = code.replace(/^export\s+(?:default\s+)?((?:async\s+)?function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => {
    exported.add(name);
    return `${kw} ${name}`;
  });
  return `__mods[${JSON.stringify(id)}] = (() => {\n${code}\nreturn { ${[...exported].join(', ')} };\n})();`;
}

function bundle() {
  const entry = path.join(SRC, 'app', 'app.js');
  const files = collect(entry);
  const js = `const __mods = {};\n${files.map(wrapModule).join('\n\n')}`;
  const css = read(path.join(SRC, 'app', 'app.css'));
  const template = fs.readFileSync(path.join(DATA, 'sheet_template.xlsx')).toString('base64');
  let html = read(path.join(SRC, 'app', 'index.html'));
  html = html
    .replace(/<link rel="stylesheet" href="app.css">/, () => `<style>\n${css}\n</style>`)
    .replace(/<script src="storage-boot.js"><\/script>/, () => `<script>\n${read(path.join(SRC, 'app', 'storage-boot.js'))}\n</script>`)
    // Phone tables: PeerJS (browser-to-browser connections) and a QR code encoder, both MIT, bundled unchanged.
    .replace(/<script src="\.\.\/vendor\/(peerjs\.min|qrcode)\.js"><\/script>/g, (_, f) => `<script>\n${read(path.join(SRC, 'vendor', `${f}.js`)).replace(/<\/script/gi, '<\\/script')}\n</script>`)
    // The 3D library is only needed for the 3D map: kept as text, so the browser doesn't parse it on every
    // start. map3d.js runs it the first time someone opens the 3D view.
    .replace(/<script src="\.\.\/vendor\/three\.min\.js"><\/script>/, () => `<script type="text/plain" id="dcugen-three">\n${read(path.join(SRC, 'vendor', 'three.min.js')).replace(/<\/script/gi, '<\\/script')}\n</script>`)
    // The app starts once its saved data has loaded from IndexedDB (storage-boot.js).
    .replace(/<script type="module" src="app.js"><\/script>/, () =>
      `<script>window.DCUGEN_SHEET_TEMPLATE = "${template}";</script>\n<script>\n(window.__dcugenStorageReady || Promise.resolve()).then(() => {\n"use strict";\n${js}\n});\n</script>`);
  // The whole app in one file at the repository root: open it, or send it to anyone.
  fs.writeFileSync(path.join(ROOT, 'DCUGen.html'), html);
  console.log(`bundle: ${files.length} modules -> DCUGen.html (${Math.round(html.length / 1024)} KB)`);
}

const step = process.argv[2] || 'all';
if (step === 'data' || step === 'all') buildData();
if (step === 'all' || step === 'bundle') bundle();
